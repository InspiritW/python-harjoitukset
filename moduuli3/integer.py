int1 = int(input("Enter the first integer: "))
int2 = int(input("Enter the second integer: "))
int3 = int(input("Enter the third integer: "))
sum_of_integers = int1 + int2 + int3
print(f"The sum of the three integers is: {sum_of_integers}")
product = int1 * int2 * int3
print(f"The product of the three integers is: {(product)}")
average = sum_of_integers / 3
print(f"The average of the three integers is: {int(average)}")